@LOSS_REGISTRY.register()
class WeightedTVLoss(L1Loss):
    """Weighted TV loss.

    Args:
        loss_weight (float): Loss weight. Default: 1.0.
    """

    def __init__(self, loss_weight=1.0, reduction='mean'):
        if reduction not in ['mean', 'sum']:
            raise ValueError(f'Unsupported reduction mode: {reduction}. Supported ones are: mean | sum')
        super(WeightedTVLoss, self).__init__(loss_weight=loss_weight, reduction=reduction)

    def forward(self, pred, weight=None):
        if weight is None:
            y_weight = None
            x_weight = None
        else:
            y_weight = weight[:, :, :-1, :]
            x_weight = weight[:, :, :, :-1]

        y_diff = super().forward(pred[:, :, :-1, :], pred[:, :, 1:, :], weight=y_weight)
        x_diff = super().forward(pred[:, :, :, :-1], pred[:, :, :, 1:], weight=x_weight)

        loss = x_diff + y_diff

        return loss

@LOSS_REGISTRY.register()
class InfoNCELoss(nn.Module):
    """InfoNCE Loss (Noise-Contrastive Estimation) for contrastive learning.

    Args:
        temperature (float): Temperature parameter scaling the similarity. Default: 0.1.
        loss_weight (float): Loss weight. Default: 1.0.
        reduction (str): Reduction mode ('none', 'mean', 'sum'). Default: 'mean'.
    """

    def __init__(self, temperature=0.1, loss_weight=1.0, reduction='mean'):
        super().__init__()
        if reduction not in ['none', 'mean', 'sum']:
            raise ValueError(f'Unsupported reduction mode: {reduction}. Supported ones are: {_reduction_modes}')

        self.temperature = temperature
        self.loss_weight = loss_weight
        self.reduction = reduction

    def forward(self, anchor, positive, negatives, weight=None, **kwargs):
        """
        Args:
            anchor (Tensor): Anchor features of shape [N, D].
            positive (Tensor): Positive features of shape [N, D] or [1, D] (broadcastable).
            negatives (Tensor): Negative features of shape [N, M, D] or [M, D] (M=num_negatives).
            weight (Tensor, optional): Sample-wise weights of shape [N]. Default: None.
        """
        # Ensure input dimensions are compatible
        if anchor.dim() != 2 or positive.dim() not in [1, 2] or negatives.dim() not in [2, 3]:
            raise ValueError(
                f'Input dims invalid: anchor={anchor.shape}, positive={positive.shape}, negatives={negatives.shape}'
            )
        # # Normalize features (L2 normalization)
        # anchor = F.normalize(anchor, dim=1)
        # positive = F.normalize(positive, dim=1)     

        # # Reshape negatives: [N, M, D] or [M, D] -> [N, M, D]
        # if negatives.dim() == 2:
        #     negatives = negatives.unsqueeze(0).expand(anchor.size(0), -1, -1)
        # negatives = F.normalize(negatives, dim=-1)  # [N, M, D]

        # print(anchor.norm(dim=-1))  # 每个样本的范数
        # print(positive.norm(dim=-1))


        # Compute similarity scores
        
        pos_sim = torch.sum(anchor * positive, dim=1, keepdim=True) / self.temperature  # [N, 1]
        neg_sim = torch.einsum('nd,nmd->nm', anchor, negatives) / self.temperature  # [N, M]
        print('Sim pos:', pos_sim.mean().item(), 'Sim neg:', neg_sim.mean().item())
        # Logits and labels for cross-entropy
        logits = torch.cat([pos_sim, neg_sim], dim=1)  # [N, 1+M]

        labels = torch.zeros(logits.size(0), dtype=torch.long, device=anchor.device)  # [N]
        # Weighted cross-entropy
        loss = F.cross_entropy(logits, labels, reduction='none')  # [N]
        if weight is not None:
            loss = loss * weight  # Sample-wise weighting

        # Apply reduction
        if self.reduction == 'mean':
            loss = loss.mean()
        elif self.reduction == 'sum':
            loss = loss.sum()

        return self.loss_weight * loss